import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_squared_error

# 示例数据（你可以将这个数据替换为你实际的数据）
# 假设我们有以下字段：新增击杀数、新增死亡数、新增伤害量、新增爆头数、爆头率、MVP次数、KD值
data_2024_12_26 = {
    "玩家ID": ["玩家1", "玩家2", "玩家3", "玩家4", "玩家5"],
    "新增击杀数": [10, 12, 8, 5, 7],
    "新增死亡数": [2, 4, 3, 1, 2],
    "新增伤害量": [300, 400, 250, 100, 200],
    "新增爆头数": [3, 5, 2, 1, 3],
    "爆头率": [0.3, 0.4, 0.25, 0.2, 0.3],
    "MVP次数": [1, 2, 1, 0, 1],
    "KD值": [5.0, 3.0, 2.5, 5.0, 3.5]
}

data_2025_01_15 = {
    "玩家ID": ["玩家1", "玩家2", "玩家3", "玩家4", "玩家5"],
    "新增击杀数": [11, 10, 6, 0, 7],
    "新增死亡数": [1, 3, 4, 0, 3],
    "新增伤害量": [320, 350, 240, 50, 180],
    "新增爆头数": [3, 3, 1, 0, 2],
    "爆头率": [0.27, 0.3, 0.2, 0.1, 0.25],
    "MVP次数": [1, 1, 0, 0, 1],
    "KD值": [5.5, 3.33, 1.5, 0, 2.33]
}

# 将数据转换为DataFrame
df_2024_12_26 = pd.DataFrame(data_2024_12_26)
df_2025_01_15 = pd.DataFrame(data_2025_01_15)

# 将"玩家ID"列设置为索引
df_2024_12_26.set_index("玩家ID", inplace=True)
df_2025_01_15.set_index("玩家ID", inplace=True)

# 计算2024年12月26号的平均水平（作为整体环境基准）
average_2024_12_26 = df_2024_12_26.mean()

# 选择特征（你可以根据需要选择不同的特征）
features = ["新增击杀数", "新增死亡数", "新增伤害量", "新增爆头数", "爆头率", "MVP次数", "KD值"]

# 分离特征和目标值
X_train = df_2024_12_26[features]  # 使用2024年12月26日的数据作为训练集
y_train = df_2024_12_26["新增击杀数"]  # 这里假设目标是预测击杀数（你可以根据需要更换目标）

# 创建并训练线性回归模型
model = LinearRegression()
model.fit(X_train, y_train)

# 对2025年1月15日的数据进行预测
X_test = df_2025_01_15[features]  # 使用2025年1月15日的数据作为测试集
y_pred = model.predict(X_test)

# 计算进步与退步
df_2025_01_15["击杀预测"] = y_pred
df_2025_01_15["击杀变化"] = df_2025_01_15["新增击杀数"] - df_2025_01_15["击杀预测"]

# 评估进步或退步（简单判断：如果预测值与实际值的变化 > 0，则进步，否则退步）
df_2025_01_15["状态"] = np.where(df_2025_01_15["击杀变化"] > 0, "进步", "退步")

# 打印结果
print(df_2025_01_15)

# 生成进步/退步图表
df_2025_01_15[["击杀变化"]].plot(kind="bar", figsize=(10, 6))
plt.title("玩家状态变化（2025年1月15日 vs 2024年12月26日）")
plt.ylabel("变化量")
plt.xlabel("玩家")
plt.show()
